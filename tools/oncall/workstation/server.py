#!/usr/bin/env python3
"""ARGUS — a terminal-style trading workstation whose order flow runs on BlazingMQ.

Stdlib only.  Orders typed into (or generated by) the workstation are posted to a
priority queue on the local broker (tcp://localhost:30114) with bmqtool.  Two real
consumers execute them: NY-PRIMARY (consumerPriority 10) and NJ-DR-STANDBY
(consumerPriority 1).  A healthy broker routes every order to NY-PRIMARY; the DR
standby must stay idle.  When the broker misroutes, the standby executes live orders
and the RECONCILIATION panel shows a break -- which is what the SEV-2 alert is about.

    tools/oncall/workstation/server.py              # http://localhost:8790
"""
import argparse
import json
import os
import random
import re
import socket
import subprocess
import threading
import time
from collections import deque
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
TOOL = os.environ.get("TOOL", os.path.join(ROOT, "build", "blazingmq", "src", "applications", "bmqtool", "bmqtool.tsk"))
ALERT = os.path.join(ROOT, "tools", "oncall", "send-alert.py")
URI = os.environ.get("URI", "bmq://bmq.test.mem.priority/argus-orders-%d" % os.getpid())
TICKERS = {"AAPL": 231.4, "MSFT": 512.1, "NVDA": 181.9, "JPM": 298.3, "GS": 771.0, "XOM": 118.6, "BAC": 51.2, "TSLA": 428.7}
PAYLOAD_RE = re.compile(r"\|(ORD-\d{4})\s*\|")

LOCK = threading.Lock()
S = {
    "orders": deque(maxlen=400),       # dicts
    "by_id": {},
    "quotes": {t: {"last": p, "chg": 0.0, "bid": p - 0.01, "ask": p + 0.01} for t, p in TICKERS.items()},
    "engines": {"NY-PRIMARY": {"priority": 10, "fills": 0, "up": False, "role": "PRIMARY"},
                "NJ-DR-STANDBY": {"priority": 1, "fills": 0, "up": False, "role": "STANDBY"}},
    "alerts": deque(maxlen=50),
    "flow": True,
    "autopage": True,
    "page": {"state": "idle", "due": None, "fired_at": None, "result": None},   # idle | countdown | paged
    "seq": 0,
    "started": time.time(),
}


def log_alert(kind, text):
    with LOCK:
        S["alerts"].appendleft({"ts": time.time(), "kind": kind, "text": text})


def git(*args):
    try:
        return subprocess.check_output(["git", "-C", ROOT, *args], text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return ""


def broker_up():
    s = socket.socket(); s.settimeout(0.4)
    try:
        s.connect(("127.0.0.1", 30114)); return True
    except OSError:
        return False
    finally:
        s.close()


class Tool:
    """One long-lived bmqtool process driven over stdin."""

    def __init__(self, name, opts, on_line):
        self.name, self.opts, self.on_line, self.p = name, opts, on_line, None

    def start(self, commands):
        self.p = subprocess.Popen([TOOL, *self.opts, "-v", "info"], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                  stderr=subprocess.STDOUT, text=True, bufsize=1)
        threading.Thread(target=self._pump, daemon=True).start()
        for c in commands:
            self.send(c)

    def _pump(self):
        for line in self.p.stdout:
            self.on_line(self.name, line)

    def send(self, cmd):
        try:
            self.p.stdin.write(cmd + "\n"); self.p.stdin.flush()
        except Exception:
            pass

    def alive(self):
        return self.p is not None and self.p.poll() is None

    def stop(self):
        if self.alive():
            self.send("stop"); self.send("quit")
            try:
                self.p.wait(3)
            except Exception:
                self.p.kill()


ENGINES = {}
PRODUCER = None


def on_engine_line(name, line):
    m = PAYLOAD_RE.search(line)
    if not m:
        return
    oid = m.group(1)
    with LOCK:
        o = S["by_id"].get(oid)
        eng = S["engines"][name]
        eng["fills"] += 1
        if o:
            o["fills"].append(name)
            o["status"] = "FILLED" if len(o["fills"]) == 1 else "DUP-FILL"
            o["site"] = "+".join(sorted(set(o["fills"])))
            o["filled_at"] = time.time()


def on_producer_line(name, line):
    pass


def start_flow():
    global PRODUCER
    if not os.path.exists(TOOL):
        log_alert("ERR", "bmqtool not built: %s" % TOOL); return
    for name, eng in S["engines"].items():
        t = Tool(name, ["--dumpmsg", "--confirmmsg"], on_engine_line)
        t.start(["start", 'open uri="%s" flags="read" consumerPriority=%d' % (URI, eng["priority"])])
        ENGINES[name] = t
        eng["up"] = True
        time.sleep(1.5)
    PRODUCER = Tool("producer", [], on_producer_line)
    PRODUCER.start(["start", 'open uri="%s" flags="write,ack"' % URI])
    time.sleep(1.0)
    log_alert("INFO", "execution engines connected to %s (NY-PRIMARY prio 10, NJ-DR-STANDBY prio 1)" % URI)


def stop_flow():
    for t in list(ENGINES.values()):
        t.stop()
    ENGINES.clear()
    if PRODUCER:
        PRODUCER.stop()
    for eng in S["engines"].values():
        eng["up"] = False


def new_order(ticker=None, side=None, qty=None):
    with LOCK:
        S["seq"] += 1
        oid = "ORD-%04d" % S["seq"]
        ticker = ticker or random.choice(list(TICKERS))
        q = S["quotes"][ticker]
        side = side or random.choice(["BUY", "SELL"])
        qty = qty or random.choice([100, 200, 250, 500, 1000, 2500])
        o = {"id": oid, "ts": time.time(), "ticker": ticker, "side": side, "qty": qty,
             "px": round(q["ask"] if side == "BUY" else q["bid"], 2), "status": "SENT", "fills": [], "site": ""}
        S["orders"].appendleft(o); S["by_id"][oid] = o
    if PRODUCER and PRODUCER.alive():
        PRODUCER.send('post uri="%s" payload=["%s"]' % (URI, oid))
    else:
        with LOCK:
            o["status"] = "REJECTED"
    return o


def market_thread():
    while True:
        with LOCK:
            for t, q in S["quotes"].items():
                move = q["last"] * random.gauss(0, 0.0006)
                q["last"] = round(q["last"] + move, 2); q["chg"] = round(q["last"] - TICKERS[t], 2)
                q["bid"] = round(q["last"] - 0.01, 2); q["ask"] = round(q["last"] + 0.01, 2)
        time.sleep(1.0)


def flow_thread(period):
    while True:
        if S["flow"] and broker_up() and PRODUCER and PRODUCER.alive():
            new_order()
        time.sleep(period)


def watchdog_thread():
    was_up = None
    while True:
        up = broker_up()
        if was_up is not None and up != was_up:
            if up:
                log_alert("INFO", "broker back on tcp://localhost:30114 — reconnecting engines")
                time.sleep(2); stop_flow(); start_flow()
            else:
                log_alert("WARN", "broker unreachable on tcp://localhost:30114 — order flow paused")
                stop_flow()
        was_up = up
        time.sleep(3)


def recon():
    with LOCK:
        orders = list(S["orders"])
    sent = len([o for o in orders if o["status"] != "REJECTED"])
    filled = [o for o in orders if o["fills"]]
    byp = sum(1 for o in filled if "NY-PRIMARY" in o["fills"])
    bys = sum(1 for o in filled if "NJ-DR-STANDBY" in o["fills"])
    dup = sum(1 for o in filled if len(o["fills"]) > 1)
    recent = filled[:6]
    rs = sum(1 for o in recent if "NJ-DR-STANDBY" in o["fills"])
    return {"sent": sent, "filled": len(filled), "by_primary": byp, "by_standby": bys, "dup": dup,
            "recent": len(recent), "recent_standby": rs, "break": bys > 0,
            "standby_share": round(100.0 * bys / len(filled)) if filled else 0}


AUTOPAGE_MIN_STANDBY = int(os.environ.get("ARGUS_AUTOPAGE_MIN_STANDBY", "3"))   # standby fills in the recent window
AUTOPAGE_DELAY = int(os.environ.get("ARGUS_AUTOPAGE_DELAY", "15"))               # seconds of countdown


def page_oncall():
    env = dict(os.environ)
    if "BMQ_SLACK_WEBHOOK_URL" in env and "SLACK_WEBHOOK_URL" not in env:
        env["SLACK_WEBHOOK_URL"] = env["BMQ_SLACK_WEBHOOK_URL"]
    with LOCK:
        recent = [o for o in list(S["orders"]) if o["fills"]][:6]
    env["ALERT_POSTED"] = str(len(recent))
    env["ALERT_PRIMARY"] = str(sum(1 for o in recent if "NY-PRIMARY" in o["fills"]))
    env["ALERT_STANDBY"] = str(sum(1 for o in recent if "NJ-DR-STANDBY" in o["fills"]))
    env["ALERT_ORDERS_PRIMARY"] = " ".join(o["id"] for o in reversed(recent) if "NY-PRIMARY" in o["fills"])
    env["ALERT_ORDERS_STANDBY"] = " ".join(o["id"] for o in reversed(recent) if "NJ-DR-STANDBY" in o["fills"])
    env["ALERT_SOURCE"] = "ARGUS workstation reconciliation monitor"
    env["ALERT_QUEUE"] = URI.replace("bmq://", "")
    with LOCK:
        S["page"].update(state="paged", due=None, fired_at=time.time())
    try:
        p = subprocess.run(["python3", ALERT], env=env, capture_output=True, text=True, timeout=30)
        out = (p.stdout + p.stderr).strip().splitlines()
        msg = out[-1] if out else "alert sender produced no output"
    except Exception as e:
        msg = "alert failed: %s" % e
    log_alert("SEV-2", "paged on-call in #bmq-oncall: priority routing violation — standby consumers receiving live traffic (%s)" % msg)
    with LOCK:
        S["page"]["result"] = msg
    return msg


def autopage_thread():
    while True:
        time.sleep(1)
        if not S["autopage"]:
            continue
        r = recon()
        with LOCK:
            pg = S["page"]
            if pg["state"] == "idle" and r["recent_standby"] >= AUTOPAGE_MIN_STANDBY:
                pg.update(state="countdown", due=time.time() + AUTOPAGE_DELAY)
                fire = False
            elif pg["state"] == "countdown":
                if r["recent_standby"] < AUTOPAGE_MIN_STANDBY:
                    pg.update(state="idle", due=None)
                fire = pg["due"] is not None and time.time() >= pg["due"]
            else:
                fire = False
        if fire:
            log_alert("SEV-2", "reconciliation break persisted %ds — raising SEV-2 and paging on-call" % AUTOPAGE_DELAY)
            page_oncall()


DEPLOY = {"state": "idle", "branch": None, "commit": None, "log": "", "started": None}


def deploy_thread(branch):
    DEPLOY.update(state="building", branch=branch, log="", started=time.time())
    log_alert("INFO", "DEPLOY %s: rebuilding broker from branch and restarting" % branch)
    steps = [["git", "-C", ROOT, "checkout", "-q", branch, "--", "src"],
             ["cmake", "--build", os.path.join(ROOT, "build", "blazingmq"), "--target", "bmqbrkr"],
             [os.path.join(ROOT, "tools", "oncall", "run-local-broker.sh"), "stop"],
             [os.path.join(ROOT, "tools", "oncall", "run-local-broker.sh"), "start"]]
    for cmd in steps:
        try:
            # the broker start script leaves a child running: never attach pipes to it
            with open("/tmp/argus-deploy.log", "a") as lf:
                p = subprocess.run(cmd, stdout=lf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, text=True, timeout=900)
            DEPLOY["log"] += "$ %s -> rc=%d\n" % (" ".join(cmd[-3:]), p.returncode)
            if p.returncode != 0:
                DEPLOY.update(state="failed")
                log_alert("ERR", "DEPLOY %s failed at: %s" % (branch, " ".join(cmd[-3:])))
                return
        except Exception as e:
            DEPLOY.update(state="failed", log=DEPLOY["log"] + str(e))
            log_alert("ERR", "DEPLOY %s failed: %s" % (branch, e))
            return
    DEPLOY.update(state="done", commit=git("rev-parse", "--short", branch))
    log_alert("INFO", "DEPLOY %s: broker restarted on %s — engines reconnecting" % (branch, DEPLOY["commit"]))


def snapshot():
    with LOCK:
        orders = [dict(o) for o in list(S["orders"])[:40]]
        quotes = {t: dict(q) for t, q in S["quotes"].items()}
        engines = {k: dict(v) for k, v in S["engines"].items()}
        alerts = list(S["alerts"])[:30]
        flow = S["flow"]
        page = dict(S["page"]); autopage = S["autopage"]
    for k, t in ENGINES.items():
        engines[k]["up"] = t.alive()
    return {"now": time.time(), "broker": broker_up(), "uri": URI, "flow": flow, "orders": orders, "quotes": quotes,
            "engines": engines, "recon": recon(), "alerts": alerts, "page": page, "autopage": autopage, "deploy": dict(DEPLOY),
            "head": ({"commit": DEPLOY["commit"], "branch": DEPLOY["branch"]} if DEPLOY.get("commit") else
                     {"commit": git("rev-parse", "--short", "HEAD"), "branch": git("rev-parse", "--abbrev-ref", "HEAD")})}


class H(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def _json(self, obj, code=200):
        b = json.dumps(obj).encode()
        self.send_response(code); self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(b))); self.end_headers(); self.wfile.write(b)

    def do_GET(self):
        if self.path.startswith("/api/state"):
            return self._json(snapshot())
        if self.path in ("/", "/index.html"):
            with open(os.path.join(HERE, "index.html"), "rb") as f:
                b = f.read()
            self.send_response(200); self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(b))); self.end_headers(); return self.wfile.write(b)
        self.send_error(404)

    def do_POST(self):
        n = int(self.headers.get("Content-Length") or 0)
        body = json.loads(self.rfile.read(n) or b"{}") if n else {}
        if self.path.startswith("/api/order"):
            return self._json(new_order(body.get("ticker"), body.get("side"), body.get("qty")))
        if self.path.startswith("/api/page"):
            return self._json({"result": page_oncall()})
        if self.path.startswith("/api/flow"):
            S["flow"] = bool(body.get("on", True)); return self._json({"flow": S["flow"]})
        if self.path.startswith("/api/deploy"):
            branch = re.sub(r"[^\w./\-]", "", body.get("branch") or "main")
            if DEPLOY["state"] == "building":
                return self._json({"error": "deploy in progress"}, 409)
            threading.Thread(target=deploy_thread, args=(branch,), daemon=True).start()
            return self._json({"ok": True, "branch": branch})
        if self.path.startswith("/api/autopage"):
            S["autopage"] = bool(body.get("on", True)); return self._json({"autopage": S["autopage"]})
        if self.path.startswith("/api/reconnect"):
            stop_flow(); start_flow(); return self._json({"ok": True})
        if self.path.startswith("/api/reset"):
            with LOCK:
                S["orders"].clear(); S["by_id"].clear()  # keep seq: IDs must never repeat (late fills)
                S["page"].update(state="idle", due=None, fired_at=None, result=None)
                for e in S["engines"].values():
                    e["fills"] = 0
            return self._json({"ok": True})
        self.send_error(404)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8790)
    ap.add_argument("--period", type=float, default=3.0, help="seconds between generated orders (0 = manual only)")
    a = ap.parse_args()
    threading.Thread(target=market_thread, daemon=True).start()
    if broker_up():
        start_flow()
    else:
        log_alert("WARN", "broker not reachable on tcp://localhost:30114 — start it with tools/oncall/run-local-broker.sh start")
    threading.Thread(target=watchdog_thread, daemon=True).start()
    threading.Thread(target=autopage_thread, daemon=True).start()
    if a.period > 0:
        threading.Thread(target=flow_thread, args=(a.period,), daemon=True).start()
    print("ARGUS workstation on http://localhost:%d  queue %s" % (a.port, URI), flush=True)
    try:
        ThreadingHTTPServer(("0.0.0.0", a.port), H).serve_forever()
    finally:
        stop_flow()


if __name__ == "__main__":
    main()
